#!/usr/bin/env python3
"""Prints a Markdown table of every JSON report in a directory."""
import glob
import json
import os
import sys


def cell(metric):
    if metric["status"] == "scored":
        return f"{metric['score']:.2f}"
    return "blocked" if metric["status"] == "blocked" else "n/a"


def main(directory):
    reports = [json.load(open(path, encoding="utf-8"))
               for path in sorted(glob.glob(os.path.join(directory, "*.json")))]
    groups = {}
    for report in reports:
        groups.setdefault(report["problem"], []).append(report)
    print("# Sample results\n")
    print("Generated by `scripts/run_demo.sh` from real runs of the agent.")
    for problem, members in groups.items():
        names = [metric["name"] for metric in members[0]["metrics"]]
        print(f"\n## {problem}\n")
        print("| Submission | Grade | Status | " + " | ".join(names) + " | Flags |")
        print("|---" * (len(names) + 4) + "|")
        for report in members:
            cells = [cell(metric) for metric in report["metrics"]]
            flags = ", ".join(flag["type"] for flag in report["flags"]) or "-"
            print(f"| `{report['submission']}` | {report['grade']:.2f} | "
                  f"{report['evaluation_status']} | " + " | ".join(cells) + f" | {flags} |")


if __name__ == "__main__":
    main(sys.argv[1])
